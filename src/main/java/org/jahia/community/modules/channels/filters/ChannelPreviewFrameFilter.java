import javax.servlet.http.HttpServletRequest;
import java.io.UnsupportedEncodingException;
import java.net.URLEncoder;
import java.text.MessageFormat;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.regex.Pattern;

/**
 * Render filter that shows the previewed page inside the frame of a device.
 * <p>
 * When the preview of a page is requested for a channel that declares a device frame (parameters
 * <code>channel</code> and <code>variant</code>), the filter answers with a small page instead of the requested one:
 * the picture of the frame, and on its screen a nested frame of the size of the screen of the device, which loads the
 * requested page with the parameter <code>noembed</code>.
 * <p>
 * The core <code>ChannelPreviewFilter</code> does the same. This filter runs before it, under the same conditions, and
 * replaces it, because the page generated by the core filter:
 * <ul>
 * <li>does not fit in the frame that jContent gives to the preview, so that scrollbars appear around the device;</li>
 * <li>shows the scrollbar of the page on the screen of the device, so that on the systems where scrollbars take
 * room the page is narrower than the screen of the device;</li>
 * </ul>
 * The variant has to be one of the variants declared by the channel.
 */
@Component(service = RenderFilter.class)
public class ChannelPreviewFrameFilter extends AbstractFilter {

    private static final Logger logger = LoggerFactory.getLogger(ChannelPreviewFrameFilter.class);

    private static final String MODULE_ID = "channels";

    // same request parameters as the core ChannelResolutionFilter and ChannelPreviewFilter
    private static final String CHANNEL_PARAMETER = "channel";
    private static final String VARIANT_PARAMETER = "variant";
    private static final String NO_EMBED_PARAMETER = "noembed";

    // the capabilities that declare a device frame, one comma-separated value per variant
    private static final String VARIANTS = "variants";
    private static final String VARIANTS_DISPLAY_NAMES = "variants-displayNames";
    private static final String FRAME_IMAGES = "decorator-images";
    private static final String FRAME_SIZES = "decorator-image-sizes";
    private static final String SCREEN_POSITIONS = "decorator-screen-positions";
    private static final String SCREEN_SIZES = "usable-resolutions";
    private static final String DISPLAY_NAME = "display-name";
    private static final String OVERLAY_SCROLLBARS = "overlay-scrollbars";

    /**
     * The characters of the path of a frame picture.
     */
    private static final Pattern SAFE_PATH = Pattern.compile("/[A-Za-z0-9_./-]+");

    static final String UNKNOWN_VARIANT_MESSAGE = "<p>Unknown variant for this device.</p>";
    static final String INVALID_FRAME_MESSAGE = "<p>The frame of this device is not configured correctly.</p>";

    @Activate
    public void activate() {
        // the core ChannelPreviewFilter has the priority 2 and the same conditions: this filter has to run first
        setPriority(1);
        setDescription("Shows the previewed page inside the frame of the device");
        setApplyOnModes("preview");
        setApplyOnConfigurations("page");
        setApplyOnTemplateTypes("html,html-.+");
    }

    @Override
    public String prepare(RenderContext renderContext, Resource resource, RenderChain chain) throws Exception {
        HttpServletRequest request = renderContext.getRequest();
        String channelIdentifier = request.getParameter(CHANNEL_PARAMETER);
        if (channelIdentifier == null || channelIdentifier.isEmpty()
                || request.getParameter(NO_EMBED_PARAMETER) != null) {
            // not the preview of a channel, or the page that is shown on the screen of the device
            return null;
        }

        if (!ChannelService.getInstance().getAllChannels().contains(channelIdentifier)) {
            // not a declared channel
            return null;
        }
        Channel channel = ChannelService.getInstance().getChannel(channelIdentifier);
        if (channel.isGeneric() || !declaresFrame(channel)) {
            // the core filter does not draw a frame either: the page is rendered as usual
            return null;
        }

        // from here the core filter would draw the frame: this filter always answers in its place
        List<String> variants = new ArrayList<>();
        for (String declared : channel.getCapability(VARIANTS).split(",")) {
            variants.add(declared.trim());
        }
        String variant = request.getParameter(VARIANT_PARAMETER);
        // without variant, the first one
        int index = variant == null || variant.isEmpty() ? 0 : variants.indexOf(variant);
        if (index < 0) {
            logger.warn("Preview of the channel {} requested with a variant that it does not declare",
                    channel.getIdentifier());
            return UNKNOWN_VARIANT_MESSAGE;
        }

        try {
            Frame frame = new Frame(channel, variants.get(index), index);
            return buildPage(renderContext, resource, frame);
        } catch (IllegalArgumentException | ArrayIndexOutOfBoundsException e) {
            logger.error("The frame of the channel {} is not configured correctly for its variant {}: {}",
                    channel.getIdentifier(), variants.get(index), e.getMessage());
            return INVALID_FRAME_MESSAGE;
        }
    }

    /**
     * Same condition as the core filter.
     */
    private static boolean declaresFrame(Channel channel) {
        return channel.hasCapabilityValue(VARIANTS) && channel.hasCapabilityValue(FRAME_SIZES)
                && channel.hasCapabilityValue(FRAME_IMAGES) && channel.hasCapabilityValue(SCREEN_POSITIONS)
                && channel.hasCapabilityValue(SCREEN_SIZES);
    }

    /**
     * The frame of a variant of a channel, as declared by its capabilities.
     */
    private static final class Frame {
        private final Channel channel;
        private final String variant;
        private final int variantIndex;
        private final String image;
        private final int[] size;
        private final int[] screenPosition;
        private final int[] screenSize;

        /**
         * @throws IllegalArgumentException       if a value is not of the expected form
         * @throws ArrayIndexOutOfBoundsException if a capability has no value for the variant
         */
        Frame(Channel channel, String variant, int variantIndex) {
            this.channel = channel;
            this.variant = variant;
            this.variantIndex = variantIndex;
            size = parsePair(channel.getCapability(FRAME_SIZES), variantIndex);
            screenPosition = parsePair(channel.getCapability(SCREEN_POSITIONS), variantIndex);
            screenSize = parsePair(channel.getCapability(SCREEN_SIZES), variantIndex);
            image = valueAt(channel.getCapability(FRAME_IMAGES), variantIndex);
            if (!SAFE_PATH.matcher(image).matches()) {
                throw new IllegalArgumentException("Unexpected characters in the path of the frame picture");
            }
        }

        private static String valueAt(String values, int index) {
            return values.split(",")[index].trim();
        }

        /**
         * Parses the value of a variant in a capability such as <code>360x800,800x360</code>.
         */
        private static int[] parsePair(String values, int index) {
            String[] pair = valueAt(values, index).split("x");
            if (pair.length != 2) {
                throw new IllegalArgumentException("Expected <number>x<number> in " + values);
            }
            return new int[]{Integer.parseInt(pair[0].trim()), Integer.parseInt(pair[1].trim())};
        }
    }

    /**
     * Returns the suffix added to the addresses of the style sheet and of the script of the generated page. Jahia
     * lets browsers cache the static files of a module for a month: without it, a browser would go on using the files
     * of the previous version of the module after an update.
     */
    private String resourcesVersion() {
        return "?v=" + FrameworkUtil.getBundle(getClass()).getLastModified();
    }

    private String buildPage(RenderContext renderContext, Resource resource, Frame frame)
            throws UnsupportedEncodingException {
        Channel channel = frame.channel;
        String variant = frame.variant;
        int variantIndex = frame.variantIndex;
        String image = frame.image;
        int[] frameSize = frame.size;
        int[] screenPosition = frame.screenPosition;
        int[] screenSize = frame.screenSize;
        String resourcesVersion = resourcesVersion();
        HttpServletRequest request = renderContext.getRequest();
        String contextPath = request.getContextPath();
        Locale locale = renderContext.getUILocale() != null ? renderContext.getUILocale() : Locale.ENGLISH;

        String deviceName = channel.hasCapabilityValue(DISPLAY_NAME) ? channel.getCapability(DISPLAY_NAME)
                : channel.getIdentifier();
        String variantName = variant;
        if (channel.hasCapabilityValue(VARIANTS_DISPLAY_NAMES)) {
            String[] names = channel.getCapability(VARIANTS_DISPLAY_NAMES).split(",");
            if (variantIndex < names.length) {
                variantName = names[variantIndex].trim();
            }
        }
        String pageTitle = message("label.channels.preview.title", "Device preview: {0} ({1})", locale, deviceName,
                variantName);
        String screenTitle = message("label.channels.preview.screen", "Preview of the page: {0} ({1})", locale,
                deviceName, variantName);

        String moduleUrl = contextPath + "/modules/" + MODULE_ID;
        StringBuilder page = new StringBuilder(1024);
        page.append("<!DOCTYPE html>\n<html lang=\"").append(escape(locale.toLanguageTag())).append("\">\n<head>\n")
                .append("<meta charset=\"UTF-8\">\n")
                .append("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n")
                .append("<title>").append(escape(pageTitle)).append("</title>\n")
                .append("<link rel=\"stylesheet\" href=\"").append(escape(moduleUrl))
                .append("/css/preview-frame.css").append(resourcesVersion).append("\">\n</head>\n<body>\n<main>\n")
                // the frame is decorative: it is a background, and has no text alternative
                .append("<div class=\"channels-frame\" style=\"width:").append(frameSize[0]).append("px;height:")
                .append(frameSize[1]).append("px;background-image:url('").append(escape(contextPath + image))
                .append("')\">\n")
                // tabindex: the screen has to be reachable with the keyboard even if the page has nothing to focus
                .append("<iframe class=\"channels-screen\" tabindex=\"0\" title=\"").append(escape(screenTitle))
                .append("\" src=\"").append(escape(screenUrl(renderContext, resource, channel, variant)))
                .append("\" width=\"").append(screenSize[0]).append("\" height=\"").append(screenSize[1])
                .append("\" style=\"left:").append(screenPosition[0]).append("px;top:").append(screenPosition[1])
                .append("px\"");
        if (Boolean.parseBoolean(channel.getCapability(OVERLAY_SCROLLBARS))) {
            page.append(" data-overlay-scrollbars=\"true\"");
        }
        page.append("></iframe>\n</div>\n</main>\n<script src=\"").append(escape(moduleUrl))
                .append("/javascript/preview-frame.js").append(resourcesVersion).append("\"></script>\n</body>\n</html>\n");
        return page.toString();
    }

    /**
     * Returns the address of the requested page, with its parameters, for the screen of the device: the channel and
     * the variant are kept, and <code>noembed</code> makes this filter let the page through.
     */
    private static String screenUrl(RenderContext renderContext, Resource resource, Channel channel, String variant)
            throws UnsupportedEncodingException {
        HttpServletRequest request = renderContext.getRequest();
        StringBuilder url = new StringBuilder(request.getContextPath());
        url.append(new URLGenerator(renderContext, resource).getCurrent());
        char separator = '?';
        for (Map.Entry<String, String[]> parameter : request.getParameterMap().entrySet()) {
            String name = parameter.getKey();
            if (CHANNEL_PARAMETER.equals(name) || VARIANT_PARAMETER.equals(name) || NO_EMBED_PARAMETER.equals(name)) {
                continue;
            }
            for (String value : parameter.getValue()) {
                url.append(separator).append(encode(name)).append('=').append(encode(value));
                separator = '&';
            }
        }
        url.append(separator).append(CHANNEL_PARAMETER).append('=').append(encode(channel.getIdentifier()))
                .append('&').append(VARIANT_PARAMETER).append('=').append(encode(variant))
                .append('&').append(NO_EMBED_PARAMETER).append("=true");
        return url.toString();
    }

    private static String encode(String value) throws UnsupportedEncodingException {
        return URLEncoder.encode(value, "UTF-8");
    }

    /**
     * Returns a label of the resource bundle of the module, or the default one if the bundle is not available.
     */
    private static String message(String key, String defaultPattern, Locale locale, Object... arguments) {
        String pattern = defaultPattern;
        JahiaTemplatesPackage module = ServicesRegistry.getInstance().getJahiaTemplateManagerService()
                .getTemplatePackageById(MODULE_ID);
        if (module != null) {
            pattern = Messages.get(module, key, locale, defaultPattern);
        }
        return new MessageFormat(pattern, locale).format(arguments);
    }

    /**
     * Escapes a text for an HTML element or a quoted HTML attribute.
     */
    static String escape(String text) {
        StringBuilder escaped = new StringBuilder(text.length() + 16);
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            switch (c) {
                case '&':
                    escaped.append("&amp;");
                    break;
                case '<':
                    escaped.append("&lt;");
                    break;
                case '>':
                    escaped.append("&gt;");
                    break;
                case '"':
                    escaped.append("&quot;");
                    break;
                case '\'':
                    escaped.append("&#39;");
                    break;
                default:
                    escaped.append(c);
            }
        }
        return escaped.toString();
    }
}
